import assert from 'node:assert/strict';
import {mkdtemp, mkdir, rm, writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const {chromium} = await import(pathToFileURL(resolve('node_modules/playwright/index.mjs')));
const {createLocalServer} = await import(pathToFileURL(resolve('mc-remote/local/launcher.mjs')));
const root = await mkdtemp(join(tmpdir(), 'scratch-local-browser-'));
let server;
let browser;
try {
    await mkdir(join(root, 'scratch'));
    await mkdir(join(root, 'wirescope'));
    await writeFile(join(root, 'scratch/index.html'), '<h1>Scratch test</h1><textarea aria-label="作品">未保存の作品</textarea><script type="module" src="/editor-tab.mjs"></script>');
    await writeFile(join(root, 'wirescope/index.html'), '<h1>WireScope test</h1>');
    await writeFile(join(root, 'identity.json'), '{}');
    const calls = [];
    const start = () => createLocalServer({root, webPort: 0, bridgePort: 8602, wireScopePort: 0,
        startBridge: async target => { calls.push(target); return async () => {}; }});
    server = await start();
    assert.deepEqual(server.openUrls, [server.url]);
    browser = await chromium.launch({executablePath: '/opt/google/chrome/chrome', headless: true, args: ['--no-sandbox']});
    const context = await browser.newContext();
    const setup = await context.newPage();
    const errors = [];
    setup.on('pageerror', error => errors.push(error.message));
    await setup.goto(server.url);
    await setup.getByRole('button', {name: 'Scratchを開く', exact: true}).waitFor();
    const popup = setup.waitForEvent('popup');
    await setup.getByRole('button', {name: 'Scratchを開く', exact: true}).click();
    const editor = await popup;
    await editor.waitForURL('**/editor/?extension=mcremote');
    await editor.getByRole('textbox', {name: '作品'}).fill('保存前の変更を維持');
    const back = setup.getByRole('button', {name: 'Scratchに戻る', exact: true});
    await back.waitFor();
    await back.click({clickCount: 3});
    assert.equal(context.pages().length, 2);
    assert.equal(await editor.getByRole('textbox', {name: '作品'}).inputValue(), '保存前の変更を維持');
    assert.equal(calls.length, 2);
    await setup.screenshot({path: 'handoff-materials/2026-10-12-b10-local-launcher-ux/materials/setup-editor-open.png', fullPage: true});
    await editor.close();
    const open = setup.getByRole('button', {name: 'Scratchを開く', exact: true});
    await open.waitFor();
    await setup.getByLabel('マインクラフトサーバーの接続先').fill('minecraft.local');
    await setup.getByLabel('McRemoteのポート', {exact: true}).fill('25576');
    const newPopup = setup.waitForEvent('popup');
    await open.click();
    const replacement = await newPopup;
    await replacement.waitForURL('**/editor/?extension=mcremote');
    assert.deepEqual(await (await fetch(`${server.url}/target`)).json(), {host: 'minecraft.local', port: 25576});
    await context.close();
    await server.close();
    server = await start();
    assert.equal(server.openUrls.length, 2);
    const restarted = await browser.newContext();
    const configTab = await restarted.newPage();
    await configTab.goto(server.openUrls[0]);
    assert.equal(await configTab.getByRole('button', {name: 'Scratchを開く', exact: true}).isDisabled(), true);
    const editorTab = await restarted.newPage();
    await editorTab.goto(server.openUrls[1]);
    const returnButton = configTab.getByRole('button', {name: 'Scratchに戻る', exact: true});
    await returnButton.waitFor();
    await returnButton.click({clickCount: 3});
    assert.equal(restarted.pages().length, 2);
    await editorTab.close();
    await configTab.getByRole('button', {name: 'Scratchを開く', exact: true}).waitFor();
    assert.deepEqual(errors, []);
    console.log('PASS: first setup, save/open, repeated clicks, unsaved contents preserved, close/change target, configured launch, separate tabs. Chromium with stub editor/Bridge; no McRemote connection or human gate test.');
} finally {
    await browser?.close();
    await server?.close();
    await rm(root, {recursive: true, force: true});
}
